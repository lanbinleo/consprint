export type Copy = (typeof copy)['en']

// Daily-rotating praise line for celebration moments (praise1..praise6).
export function praiseKey(): 'praise1' | 'praise2' | 'praise3' | 'praise4' | 'praise5' | 'praise6' {
  const index = (Math.floor(Date.now() / 86_400_000) % 6) + 1
  return `praise${index}` as 'praise1' | 'praise2' | 'praise3' | 'praise4' | 'praise5' | 'praise6'
}

export function getCopy(lang: Lang): Copy {
  return copy[lang] as Copy
}

export function detectLang(): Lang {
  const stored = localStorage.getItem('apPsychLang')
  if (stored === 'en' || stored === 'zh') return stored
  return navigator.language.toLowerCase().startsWith('zh') ? 'zh' : 'en'
}
